import { stringify } from 'yaml';
import { OPENAPI_INFO, createApp } from './app.js';
import type { Deps } from './deps.js';

/** Renders contracts/openapi.yaml from the Zod route schemas. Handlers never run, so no real deps are needed. */
export function renderOpenApiYaml(): string {
  const app = createApp({} as Deps);
  const doc = app.getOpenAPI31Document(OPENAPI_INFO);
  return `# Generated by \`npm run openapi\` from the Zod route schemas. Do not edit by hand.\n${stringify(doc, { aliasDuplicateObjects: false })}`;
}
